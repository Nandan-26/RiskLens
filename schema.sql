CREATE DATABASE IF NOT EXISTS risklens_db CHARACTER SET utf8mb4;
CREATE DATABASE IF NOT EXISTS risklens_test_db CHARACTER SET utf8mb4;
USE risklens_db;
CREATE TABLE IF NOT EXISTS businesses (id INT AUTO_INCREMENT PRIMARY KEY,
 company_name VARCHAR(255) NOT NULL,
 registration_number VARCHAR(100) UNIQUE NOT NULL,
 country VARCHAR(100) NOT NULL,
 industry VARCHAR(100), contact_email VARCHAR(255), founded_year INT,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS scraped_books (id INT AUTO_INCREMENT PRIMARY KEY, title VARCHAR(255) NOT NULL,
 price VARCHAR(50) NOT NULL, rating VARCHAR(50) NOT NULL,
 product_url VARCHAR(500) UNIQUE NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP);
